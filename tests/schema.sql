CREATE DATABASE IF NOT EXISTS simulador_urna_test CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE simulador_urna_test;

CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 email VARCHAR(160) NOT NULL UNIQUE,
 senha_hash VARCHAR(255) NOT NULL,
 perfil ENUM('ADMIN','OPERADOR') NOT NULL DEFAULT 'OPERADOR',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS eleicoes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(150) NOT NULL,
 descricao TEXT NULL,
 status ENUM('RASCUNHO','EM_ANDAMENTO','ENCERRADA') NOT NULL DEFAULT 'RASCUNHO',
 data_inicio DATETIME NULL,
 data_fim DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS eleitores (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 identificador VARCHAR(50) NOT NULL UNIQUE,
 nome VARCHAR(120) NOT NULL,
 senha_hash VARCHAR(255) NOT NULL,
 status ENUM('ATIVO','BLOQUEADO') NOT NULL DEFAULT 'ATIVO',
 votou BOOLEAN NOT NULL DEFAULT FALSE,
 eleicao_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_eleitores_eleicao FOREIGN KEY (eleicao_id) REFERENCES eleicoes(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS partidos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 sigla VARCHAR(12) NOT NULL UNIQUE,
 numero SMALLINT UNSIGNED NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS candidatos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nome VARCHAR(120) NOT NULL,
 numero SMALLINT UNSIGNED NOT NULL,
 cargo VARCHAR(80) NOT NULL,
 foto VARCHAR(255) NULL,
 partido_id BIGINT UNSIGNED NOT NULL,
 eleicao_id BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_candidatos_partido FOREIGN KEY (partido_id) REFERENCES partidos(id),
 CONSTRAINT fk_candidatos_eleicao FOREIGN KEY (eleicao_id) REFERENCES eleicoes(id),
 CONSTRAINT uq_candidato_eleicao UNIQUE (eleicao_id, numero)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS votos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 eleicao_id BIGINT UNSIGNED NOT NULL,
 eleitor_id BIGINT UNSIGNED NOT NULL,
 candidato_id BIGINT UNSIGNED NULL,
 tipo ENUM('VALIDO','BRANCO','NULO') NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_votos_eleicao FOREIGN KEY (eleicao_id) REFERENCES eleicoes(id),
 CONSTRAINT fk_votos_eleitor FOREIGN KEY (eleitor_id) REFERENCES eleitores(id),
 CONSTRAINT fk_votos_candidato FOREIGN KEY (candidato_id) REFERENCES candidatos(id),
 CONSTRAINT uq_voto_por_eleitor_eleicao UNIQUE (eleicao_id, eleitor_id),
 CONSTRAINT chk_voto_candidato CHECK ((tipo = 'VALIDO' AND candidato_id IS NOT NULL) OR (tipo IN ('BRANCO','NULO') AND candidato_id IS NULL))
) ENGINE=InnoDB;
